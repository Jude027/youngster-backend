const mongoose = require('mongoose');

const paymentTransactionSchema = new mongoose.Schema({
    userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    orderId: { type: mongoose.Schema.Types.ObjectId, ref: 'Order' },
    storeSlug: { type: String, index: true },
    clientType: String,
    
    // Payment Details
    paymentGateway: String, // e.g., "Korba Xchange"
    provider: String, // e.g., "MTN", "Telecel"
    paymentNetwork: String, // MoMo network used to pay, e.g., "MTN"
    phoneNumber: String, // Customer phone number
    amount: Number, // Amount to be charged
    currency: { type: String, default: 'GHS' },
    
    // Transaction Tracking
    transactionId: { type: String, unique: true }, // Unique ID generated by our system
    gatewayTransactionId: String, // Transaction ID returned by payment gateway
    
    // Payment Status
    status: { type: String, enum: ['pending', 'processing', 'otp_verified', 'success', 'failed', 'cancelled'], default: 'pending' },
    paymentMethod: String, // "mobile_money", "card", "bank_transfer"
    
    // Fees & Final Amount
    transactionFee: { type: Number, default: 0 },
    totalAmount: Number, // amount + fee
    
    // Gateway Response
    gatewayResponse: mongoose.Schema.Types.Mixed,
    redirectUrl: String, // For card payments, URL to complete payment
    
    // Metadata
    description: String,
    packageName: { type: String, default: '' },
    bundle: { type: String, default: '' },
    metadata: mongoose.Schema.Types.Mixed,

    // When true, the beneficiary number failed verification before payment was
    // initiated. The order is routed through the secondary API config flagged
    // forUnverifiedNumbers: true on the Provider (if one is configured).
    isUnverified: { type: Boolean, default: false },

    // Atomic mutex shared by pending-record creation and paid-order creation.
    orderCreating: { type: Boolean, default: false },

    // Set when an attempt has remained inconclusive long enough for manual
    // reconciliation. Even if later confirmed paid, do not auto-route it.
    manualReconciliationRequired: { type: Boolean, default: false },

    // Timestamps
    initiatedAt: { type: Date, default: Date.now },
    completedAt: Date,

    // Set when OTP is verified (Moolre 3-step flow). Used by checkPaymentStatus
    // to apply a 10s grace period before polling Moolre's status endpoint —
    // Moolre won't register the transaction until the customer responds to the
    // USSD prompt.
    otpVerifiedAt: { type: Date, default: null },
    
    // Retry Information
    retryCount: { type: Number, default: 0 },
    lastRetryAt: Date,
    
    // Error Tracking
    errorMessage: String,
    errorCode: String
});

module.exports = mongoose.model('PaymentTransaction', paymentTransactionSchema);
